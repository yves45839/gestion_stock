from pathlib import Path

from django.conf import settings
from django.contrib import messages
from django.core.exceptions import PermissionDenied
from django.http import FileResponse, Http404
from django.shortcuts import get_object_or_404, redirect, render
from django.views.decorators.cache import never_cache
from django.views.decorators.http import require_http_methods, require_POST

from inventory.models import DocumentDelivery, Sale
from .documents import DocumentError, allowed_site, batch_folder, check_sale, prepare_attachments, report_snapshot
from .forms import DeliveryForm
from .providers import DeliveryError, email_send, preflight, whatsapp_send


def enabled():
    if not settings.DOCUMENT_DELIVERY_ENABLED:
        raise Http404("Les essais d’envoi ne sont pas activés.")


def owned_batch(request, pk):
    enabled()
    batch = get_object_or_404(DocumentDelivery.objects.select_related("sale", "site"), pk=pk, requested_by=request.user)
    if batch.sale_id:
        check_sale(request, batch.sale)
    elif not request.user.is_superuser and batch.site_id != allowed_site(request).pk:
        raise PermissionDenied("Votre site ne peut pas accéder à cet envoi.")
    return batch


@never_cache
@require_http_methods(["GET", "POST"])
def compose(request, pk=None, doc_type="report"):
    enabled()
    sale = None
    if doc_type == "report":
        site, filters = report_snapshot(request)
        title = "Rapport des ventes confirmées"
    else:
        if doc_type not in {"quote", "invoice"}:
            raise Http404("Document inconnu.")
        sale = get_object_or_404(Sale.objects.select_related("customer").prefetch_related("items__product"), pk=pk)
        check_sale(request, sale)
        from inventory.views import _get_document_meta
        meta = _get_document_meta(sale, doc_type)
        title, site, filters = f"{meta['title']} {meta['reference']}", sale.site, {}
    initial = {"channels": ["email"], "file_format": "pdf", "subject": title,
               "message": f"Bonjour, veuillez trouver ci-joint votre {title.lower()}. Cordialement, LrStock.",
               "email": sale.customer.email if sale and sale.customer else "",
               "phone": sale.customer.phone if sale and sale.customer else ""}
    form = DeliveryForm(request.POST if request.method == "POST" else None, initial=initial, report=doc_type == "report")
    if request.method == "POST" and form.is_valid():
        data = form.cleaned_data
        batch = DocumentDelivery.objects.create(requested_by=request.user, sale=sale, site=site,
            document_type=doc_type, file_format=data["file_format"], title=title, subject=data["subject"],
            message=data["message"], channels=data["channels"], report_filters=filters,
            destinations={"email": data["email"], "phone": data["phone"], "sender": settings.DOCUMENT_EMAIL_SENDER}, simulated=settings.DOCUMENT_DELIVERY_SIMULATE)
        try:
            batch.attachments = prepare_attachments(request, batch)
            batch.status = "ready"
            batch.save(update_fields=["attachments", "status", "updated_at"])
            return redirect("inventory:delivery_detail", pk=batch.pk)
        except (DocumentError, OSError, ValueError) as error:
            batch.status = "failed"
            batch.save(update_fields=["status", "updated_at"])
            form.add_error(None, str(error) if isinstance(error, DocumentError) else "La pièce jointe n’a pas pu être préparée. Réessayez ou contactez l’administrateur.")
    return render(request, "inventory/delivery_compose.html", {"form": form, "document_title": title,
        "simulation": settings.DOCUMENT_DELIVERY_SIMULATE, "report_site": site, "sender_email": settings.DOCUMENT_EMAIL_SENDER})


@never_cache
@require_http_methods(["GET"])
def detail(request, pk):
    return render(request, "inventory/delivery_detail.html", {"delivery": owned_batch(request, pk)})


@never_cache
@require_http_methods(["GET"])
def attachment(request, pk, index):
    batch = owned_batch(request, pk)
    if not 0 <= index < len(batch.attachments):
        raise Http404("Pièce jointe inconnue.")
    item = batch.attachments[index]
    # Only filenames generated by our renderer are allowed, never a URL or user path.
    if Path(item["name"]).name != item["name"]:
        raise Http404()
    path = batch_folder(batch) / item["name"]
    if not path.is_file():
        raise Http404("La pièce jointe n’est plus disponible.")
    response = FileResponse(path.open("rb"), content_type=item["mimetype"], as_attachment=True, filename=item["name"])
    response["Cache-Control"] = "private, no-store"
    response["X-Content-Type-Options"] = "nosniff"
    return response


@never_cache
@require_POST
def send(request, pk):
    batch = owned_batch(request, pk)
    if request.POST.get("confirm") != "yes":
        messages.error(request, "Confirmez le destinataire et les pièces jointes.")
        return redirect("inventory:delivery_detail", pk=pk)
    try:
        preflight(batch)
    except DeliveryError as error:
        messages.error(request, str(error))
        return redirect("inventory:delivery_detail", pk=pk)
    # Atomic claim: double clicks, refreshes and parallel requests cannot send twice.
    if DocumentDelivery.objects.filter(pk=pk, status="ready").update(status="sending") != 1:
        messages.info(request, "Cet envoi est déjà traité ou en cours. Aucun nouvel envoi n’a été déclenché.")
        return redirect("inventory:delivery_detail", pk=pk)
    for channel in batch.channels:
        items = batch.attachments if channel == "whatsapp" else [None]
        for item in items:
            result = {"channel": channel, "file": item["name"] if item else "Toutes les pièces jointes"}
            try:
                if batch.simulated:
                    result.update(status="simulated", description="Simulation : aucun message envoyé.")
                else:
                    provider_id = email_send(batch) if channel == "email" else whatsapp_send(batch, item)
                    result.update(status="accepted", provider_id=provider_id, description="Accepté par le prestataire ; réception non confirmée.")
            except DeliveryError as error:
                result.update(status="uncertain" if error.uncertain else "failed", description=str(error))
            except Exception:
                result.update(status="uncertain", description="Confirmation indisponible. Vérifiez avant tout nouvel essai.")
            batch.results.append(result)
            # Save after each external operation: preserve partial successes.
            batch.save(update_fields=["results", "updated_at"])
    batch.status = "completed"
    batch.save(update_fields=["status", "updated_at"])
    return redirect("inventory:delivery_detail", pk=pk)


@never_cache
@require_http_methods(["GET"])
def history(request):
    enabled()
    deliveries = DocumentDelivery.objects.filter(requested_by=request.user)[:50]
    return render(request, "inventory/delivery_history.html", {"deliveries": deliveries})
